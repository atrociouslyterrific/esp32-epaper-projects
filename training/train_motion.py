"""Teach Pip how to move: a small generative model (a GRU) that writes movement clips.

It reads what Pip is doing, its mood and its energy, then writes a clip one value at a time:
sideways step, jump height, squash, sideways step, ... until it decides the clip is over.
Runs on GitHub Actions. Outputs:
  PipAI/pip_motion.h            - the model (8-bit weights) + a C clip generator
  training/out/motion_test.txt  - clips the C test must reproduce exactly
  status.json "motion"          - progress + example clips for the status website
"""
import json
import os
import sys
import time

import numpy as np
import torch
import torch.nn as nn

torch.set_num_threads(int(os.environ.get("PIP_MOTION_THREADS", "1")))  # small model: 1 core is plenty

sys.path.insert(0, os.path.dirname(__file__))
import motion_corpus as MC  # noqa: E402

SEED = 21
HIDDEN = 96
STEPS = int(os.environ.get("PIP_MOTION_STEPS", "2500"))
BATCH, SEQ, LR = 128, 96, 3e-3

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "training", "out")
STATUS_PATH = os.path.join(OUT, "status.json")

# Tokens: END, then the context (action, mood, energy), then the three kinds of frame values
VOCAB = (["END"] + [f"a:{a}" for a in MC.ACTIONS] + [f"m:{m}" for m in MC.MOODS] + [f"e:{e}" for e in MC.ENERGY]
         + [f"dx:{v}" for v in MC.DX_VALUES] + [f"jy:{v}" for v in MC.JUMP_VALUES] + [f"sq:{v}" for v in MC.SQ_VALUES])
IDX = {t: i for i, t in enumerate(VOCAB)}
V = len(VOCAB)
DX0, JY0, SQ0 = IDX[f"dx:{MC.DX_VALUES[0]}"], IDX[f"jy:{MC.JUMP_VALUES[0]}"], IDX[f"sq:{MC.SQ_VALUES[0]}"]
NDX, NJY, NSQ = len(MC.DX_VALUES), len(MC.JUMP_VALUES), len(MC.SQ_VALUES)


def tokens(action, mood, energy, frames):
    t = [IDX[f"a:{action}"], IDX[f"m:{mood}"], IDX[f"e:{energy}"]]
    for dx, jy, sq in frames:
        t += [IDX[f"dx:{dx}"], IDX[f"jy:{jy}"], IDX[f"sq:{sq}"]]
    return t + [IDX["END"]]


class Motion(nn.Module):
    def __init__(self):
        super().__init__()
        self.gru = nn.GRU(V, HIDDEN, batch_first=True)
        self.out = nn.Linear(HIDDEN, V)

    def forward(self, x, h=None):
        y, h = self.gru(nn.functional.one_hot(x, V).float(), h)
        return self.out(y), h


def allowed(slot, n_frames):
    """Which tokens may come next: a step (or END), then a jump, then a squash."""
    if slot == 0:
        return list(range(DX0, DX0 + NDX)) + ([IDX["END"]] if n_frames > 0 else [])
    if slot == 1:
        return list(range(JY0, JY0 + NJY))
    return list(range(SQ0, SQ0 + NSQ))


def generate(model, action, mood, energy, temperature=0.8, rng=None):
    with torch.no_grad():
        h = None
        for t in [IDX[f"a:{action}"], IDX[f"m:{mood}"], IDX[f"e:{energy}"]]:
            logits, h = model(torch.tensor([[t]]), h)
        frames, cur = [], []
        for _ in range(MC.MAX_FRAMES * 3):
            ok = allowed(len(cur), len(frames))
            l = logits[0, -1].numpy()[ok]
            if temperature <= 0:
                k = ok[int(np.argmax(l))]
            else:
                p = np.exp((l - l.max()) / temperature)
                k = ok[int(rng.choice(len(ok), p=p / p.sum()))]
            if VOCAB[k] == "END":
                break
            cur.append(int(VOCAB[k].split(":")[1]))
            if len(cur) == 3:
                frames.append(tuple(cur))
                cur = []
            logits, h = model(torch.tensor([[k]]), h)
        return frames


def update_status(**motion):
    try:
        s = json.load(open(STATUS_PATH))
    except Exception:
        s = {}
    s.setdefault("motion", {}).update(motion)
    tmp = STATUS_PATH + ".m.tmp"
    json.dump(s, open(tmp, "w"))
    os.replace(tmp, STATUS_PATH)


def quantize_rows(w):
    w = w.detach().numpy().astype(np.float32)
    scale = np.maximum(np.abs(w).max(axis=1), 1e-8) / 127.0
    q = np.clip(np.round(w / scale[:, None]), -127, 127).astype(np.int8)
    return q, scale.astype(np.float32)


def quantized_copy(model):
    qm = Motion()
    qm.load_state_dict(model.state_dict())
    with torch.no_grad():
        for w in (qm.gru.weight_ih_l0, qm.gru.weight_hh_l0, qm.out.weight):
            q, sc = quantize_rows(w)
            w.copy_(torch.from_numpy(q.astype(np.float32) * sc[:, None]))
    qm.eval()
    return qm


def c_floats(name, a):
    a = np.asarray(a, dtype=np.float32).ravel()
    return f"static const float {name}[{a.size}] = {{" + ",".join(f"{v:.7g}f" for v in a) + "};\n"


def c_int8(name, q):
    q = q.ravel()
    return f"static const int8_t {name}[{q.size}] = {{" + ",".join(str(int(v)) for v in q) + "};\n"


def export(model, path, version):
    g = model.gru
    with open(path, "w") as f:
        f.write("// Pip's motion model: a small generative GRU that writes movement clips.\n")
        f.write("// GENERATED by training/train_motion.py - do not edit by hand.\n#pragma once\n#include <math.h>\n#include <stdint.h>\n\n")
        f.write(f"#define PM_VERSION {version}\n#define PM_V {V}\n#define PM_H {HIDDEN}\n#define PM_MAX_FRAMES {MC.MAX_FRAMES}\n")
        f.write(f"#define PM_ACT0 {IDX['a:' + MC.ACTIONS[0]]}\n#define PM_MOOD0 {IDX['m:' + MC.MOODS[0]]}\n#define PM_EN0 {IDX['e:' + MC.ENERGY[0]]}\n")
        f.write(f"#define PM_DX0 {DX0}\n#define PM_NDX {NDX}\n#define PM_JY0 {JY0}\n#define PM_NJY {NJY}\n#define PM_SQ0 {SQ0}\n#define PM_NSQ {NSQ}\n")
        f.write("// actions: " + " ".join(MC.ACTIONS) + " | moods: " + " ".join(MC.MOODS) + " | energy: " + " ".join(MC.ENERGY) + "\n")
        f.write("static const int8_t PM_DX[PM_NDX] = {" + ",".join(map(str, MC.DX_VALUES)) + "};\n")
        f.write("static const int8_t PM_JY[PM_NJY] = {" + ",".join(map(str, MC.JUMP_VALUES)) + "};\n")
        f.write("static const uint8_t PM_SQ[PM_NSQ] = {" + ",".join(map(str, MC.SQ_VALUES)) + "};\n\n")
        for name, w in [("PM_WIH", g.weight_ih_l0), ("PM_WHH", g.weight_hh_l0), ("PM_WO", model.out.weight)]:
            q, sc = quantize_rows(w)
            f.write(c_int8(name + "Q", q))
            f.write(c_floats(name + "S", sc))
        f.write(c_floats("PM_BIH", g.bias_ih_l0.detach().numpy()))
        f.write(c_floats("PM_BHH", g.bias_hh_l0.detach().numpy()))
        f.write(c_floats("PM_BO", model.out.bias.detach().numpy()))
        f.write("""
static inline float pm_sig(float x) { return 1.0f / (1.0f + expf(-x)); }

static void pm_step(float *h, int tok) {
  float hn[PM_H];
  for (int j = 0; j < PM_H; j++) {
    const int8_t *wr = PM_WHHQ + j * PM_H, *wz = PM_WHHQ + (PM_H + j) * PM_H, *wn = PM_WHHQ + (2 * PM_H + j) * PM_H;
    float ar = 0, az = 0, an = 0;
    for (int k = 0; k < PM_H; k++) { ar += (float)wr[k] * h[k]; az += (float)wz[k] * h[k]; an += (float)wn[k] * h[k]; }
    float r = pm_sig((float)PM_WIHQ[j * PM_V + tok] * PM_WIHS[j] + PM_BIH[j] + PM_BHH[j] + PM_WHHS[j] * ar);
    float z = pm_sig((float)PM_WIHQ[(PM_H + j) * PM_V + tok] * PM_WIHS[PM_H + j] + PM_BIH[PM_H + j] + PM_BHH[PM_H + j] + PM_WHHS[PM_H + j] * az);
    float n = tanhf((float)PM_WIHQ[(2 * PM_H + j) * PM_V + tok] * PM_WIHS[2 * PM_H + j] + PM_BIH[2 * PM_H + j] +
                    r * (PM_BHH[2 * PM_H + j] + PM_WHHS[2 * PM_H + j] * an));
    hn[j] = (1 - z) * n + z * h[j];
  }
  for (int j = 0; j < PM_H; j++) h[j] = hn[j];
}

// Write a movement clip for (action, mood, energy) - see the lists above for their numbers.
// Fills dx (sideways step), jump (height; negative = up) and squash (%), returns the frame count.
// temperature 0 = always the most likely value (used by the test).
static int pm_generate(int action, int mood, int energy, int8_t *dx, int8_t *jump, uint8_t *squash, int maxFrames,
                       float temperature, float (*rand01)(void)) {
  float h[PM_H] = {0}, lg[PM_V];
  pm_step(h, PM_ACT0 + action);
  pm_step(h, PM_MOOD0 + mood);
  pm_step(h, PM_EN0 + energy);
  int frames = 0, slot = 0;
  if (maxFrames > PM_MAX_FRAMES) maxFrames = PM_MAX_FRAMES;
  for (int guard = 0; guard < PM_MAX_FRAMES * 3; guard++) {
    // only some tokens may come next: a step (or the end), then a jump, then a squash
    int lo = slot == 0 ? PM_DX0 : slot == 1 ? PM_JY0 : PM_SQ0;
    int n = slot == 0 ? PM_NDX : slot == 1 ? PM_NJY : PM_NSQ;
    int allowEnd = slot == 0 && frames > 0;
    for (int v = 0; v < PM_V; v++) {
      float s = PM_BO[v];
      const int8_t *row = PM_WOQ + v * PM_H;
      float acc = 0;
      for (int k = 0; k < PM_H; k++) acc += (float)row[k] * h[k];
      lg[v] = s + PM_WOS[v] * acc;
    }
    int pick = -1;
    if (temperature <= 0) {
      for (int v = lo; v < lo + n; v++) if (pick < 0 || lg[v] > lg[pick]) pick = v;
      if (allowEnd && lg[0] > lg[pick]) pick = 0;
    } else {
      float mx = -1e30f, sum = 0, p[64];
      for (int i = 0; i < n; i++) if (lg[lo + i] > mx) mx = lg[lo + i];
      if (allowEnd && lg[0] > mx) mx = lg[0];
      for (int i = 0; i < n; i++) { p[i] = expf((lg[lo + i] - mx) / temperature); sum += p[i]; }
      float pend = allowEnd ? expf((lg[0] - mx) / temperature) : 0;
      sum += pend;
      float r = rand01() * sum, acc = 0;
      pick = lo + n - 1;
      for (int i = 0; i < n; i++) { acc += p[i]; if (r < acc) { pick = lo + i; break; } }
      if (allowEnd && r >= sum - pend) pick = 0;
    }
    if (pick == 0) break;                                     // the model ended the clip
    if (slot == 0) dx[frames] = PM_DX[pick - PM_DX0];
    else if (slot == 1) jump[frames] = PM_JY[pick - PM_JY0];
    else { squash[frames] = PM_SQ[pick - PM_SQ0]; frames++; if (frames >= maxFrames) break; }
    slot = (slot + 1) % 3;
    pm_step(h, pick);
  }
  return frames;
}
""")


TEST_CASES = [(a, m, "mid") for a in MC.ACTIONS for m in ("happy", "tired")] + [("fidget", "grumpy", "low"), ("play", "sad", "high")]


def main():
    os.makedirs(OUT, exist_ok=True)
    torch.manual_seed(SEED)
    rng = np.random.default_rng(SEED)
    stream = np.array([t for a, m, e, f in MC.make_examples(40000, SEED) for t in tokens(a, m, e, f)], dtype=np.int64)
    model = Motion()
    opt = torch.optim.Adam(model.parameters(), lr=LR)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, STEPS)
    start, losses = time.time(), []
    update_status(state="training", step=0, total=STEPS)
    for step in range(STEPS):
        starts = rng.integers(0, len(stream) - SEQ - 1, BATCH)
        x = torch.from_numpy(np.stack([stream[s:s + SEQ] for s in starts]))
        y = torch.from_numpy(np.stack([stream[s + 1:s + SEQ + 1] for s in starts]))
        logits, _ = model(x)
        loss = nn.functional.cross_entropy(logits.reshape(-1, V), y.reshape(-1))
        opt.zero_grad()
        loss.backward()
        nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        opt.step()
        sched.step()
        if step % 250 == 0 or step == STEPS - 1:
            losses.append(round(float(loss), 4))
            update_status(state="training", step=step + 1, total=STEPS, loss=losses, elapsed_s=round(time.time() - start))
            print(f"motion step {step:5d} loss {float(loss):.3f}", flush=True)
    model.eval()
    version = int(os.environ.get("GITHUB_RUN_NUMBER", "1"))
    export(model, os.path.join(ROOT, "PipAI", "pip_motion.h"), version)
    board = quantized_copy(model)
    with open(os.path.join(OUT, "motion_test.txt"), "w") as f:
        for a, m, e in TEST_CASES:
            frames = generate(board, a, m, e, 0)
            f.write(f"{MC.ACTIONS.index(a)} {MC.MOODS.index(m)} {MC.ENERGY.index(e)} {len(frames)}"
                    + "".join(f" {dx} {jy} {sq}" for dx, jy, sq in frames) + "\n")
    srng = np.random.default_rng(3)
    examples = {f"{a}/{m}": generate(board, a, m, "mid", 0.8, srng) for a, m in
                [("play", "happy"), ("play", "tired"), ("explore", "happy"), ("dance", "happy"), ("fidget", "grumpy"), ("hide", "sad")]}
    update_status(state="done", step=STEPS, version=version, examples=examples)
    print("motion: done", flush=True)


if __name__ == "__main__":
    main()
